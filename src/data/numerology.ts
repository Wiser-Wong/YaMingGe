export function numerology(n: number): { luck: Luck; title: string; desc: string } {
  let k = n;
  while (k > 81) k -= 80;
  if (k < 1) k = 1;
  const [luck, title, desc] = TABLE[k];
  return { luck, title, desc };
}

/** 数字的五行（尾数 1,2木 3,4火 5,6土 7,8金 9,0水） */
export function numberWx(n: number): WuXing {
  const t = n % 10;
  if (t === 1 || t === 2) return '木';
  if (t === 3 || t === 4) return '火';
  if (t === 5 || t === 6) return '土';
  if (t === 7 || t === 8) return '金';
  return '水';
}

export function luckScore(l: Luck): number {
  return l === '吉' ? 100 : l === '半吉' ? 70 : 40;
}
