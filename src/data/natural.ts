const RAW_STYLE_GENDER: Record<string, CharGender> = { M: 'M', F: 'F' };

function parse(list: string[]): NaturalName[] {
  return list.map((row) => {
    const [given, note, g] = row.split('|');
    return { given, note, gender: g ? RAW_STYLE_GENDER[g] ?? 'N' : 'N' };
  });
}

/** 姓氏 → 浑然天成候选名 */
export const NATURAL_MAP: Map<string, NaturalName[]> = new Map(
  Object.entries(RAW).map(([surname, rows]) => [surname, parse(rows)]),
);

/** 按姓氏读音（复姓取末字）自动匹配的谐音成词候选，同音姓氏共享 */
function homophoneNaturals(surname: string): NaturalName[] {
  const py = lookupSurname(surname).py.split(' ').pop() ?? '';
  const plain = splitPinyin(py).plain;
  if (!plain) return [];
  const last = Array.from(surname).pop();
  return homophoneFor(plain)
    .filter((e) => e.given !== last)
    .map((e) => ({ given: e.given, note: `${last && e.word.startsWith(last) ? '成' : '谐'}「${e.word}」，${e.meaning}`, gender: e.gender ?? 'N' }));
}

/** 手工词条优先，其后追加谐音成词，按名去重 */
function allNaturals(surname: string): NaturalName[] {
  const manual = NATURAL_MAP.get(surname) ?? [];
  const used = new Set(manual.map((n) => n.given));
  const extra = homophoneNaturals(surname).filter((n) => !used.has(n.given) && used.add(n.given));
  return [...manual, ...extra];
}

/** 该姓氏是否有浑然天成之名 */
export function hasNatural(surname: string): boolean {
  return NATURAL_MAP.has(surname) || homophoneNaturals(surname).length > 0;
}

/** 按性别过滤后的浑然天成候选（中性名两性通用） */
export function naturalFor(surname: string, gender: 'M' | 'F'): NaturalName[] {
  return allNaturals(surname).filter((n) => !n.gender || n.gender === 'N' || n.gender === gender);
}
