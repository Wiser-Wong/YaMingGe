function build(row: Row): CharInfo {
  const [ch, py, wx, strokes, meaning, gender, styleCodes, tagCodes, pop, source] = row;
  return {
    ch,
    py,
    wx,
    strokes,
    meaning,
    gender,
    styles: styleCodes.split('').map((c) => STYLE_MAP[c]).filter(Boolean),
    tags: tagCodes.split('').map((c) => TAG_MAP[c]).filter(Boolean),
    pop,
    source,
  };
}

const seen = new Set<string>();
export const CHARACTERS: CharInfo[] = ROWS.filter((r) => {
  if (seen.has(r[0])) return false;
  seen.add(r[0]);
  return true;
}).map(build);

export const CHAR_MAP: Map<string, CharInfo> = new Map(CHARACTERS.map((c) => [c.ch, c]));

// 补充字表：仅供查询（浑然天成 / 名字测试），不进入 CHARACTERS 候选池
for (const [ch, py, wx, strokes, meaning] of EXTRA_ROWS) {
  if (!CHAR_MAP.has(ch)) CHAR_MAP.set(ch, { ch, py, wx, strokes, meaning, gender: 'N', styles: ['poetic'], tags: [], pop: 3 });
}

/** 查询字库；未收录时返回估算信息 */
export function lookupChar(ch: string): CharInfo {
  const found = CHAR_MAP.get(ch);
  if (found) return found;
  return {
    ch,
    py: '',
    wx: '土',
    strokes: 10,
    meaning: '该字暂未收录，五行与笔画为估算',
    gender: 'N',
    styles: [],
    tags: [],
    pop: 2,
    unknown: true,
  };
}
