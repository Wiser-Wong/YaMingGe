/** 解析姓氏（支持复姓、字库回退） */
export function lookupSurname(raw: string): SurnameInfo {
  const s = raw.trim();
  const direct = SURNAME_MAP.get(s);
  if (direct) return direct;
  if (s.length >= 2) {
    // 复姓：逐字拼接
    const parts = Array.from(s).map((c) => lookupSurname(c));
    return {
      ch: s,
      py: parts.map((p) => p.py).join(' '),
      wx: parts[0].wx,
      strokes: parts.reduce((a, p) => a + p.strokes, 0),
      rank: 300,
    };
  }
  const c = CHAR_MAP.get(s);
  if (c) return { ch: s, py: c.py, wx: c.wx, strokes: c.strokes, rank: 250 };
  return { ch: s, py: '', wx: '土', strokes: 10, rank: 300 };
}
